/**
 * orm-china-viewer · deterministic client bundle builder (02-plan §5).
 * Zero dependencies: concatenates three parts into client.js:
 *   1. Leaflet dist wrapped in a forced-CommonJS bridge (sets window.L)
 *   2. window.__ORM_LEAFLET_CSS__ = <leaflet.css as a JSON string>
 *   3. src/client.js verbatim (reads the CSS global and appends panel CSS)
 * Run: node scripts/build-client.mjs   (idempotent; output is committed)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const leafletJs = readFileSync(path.join(root, "vendor", "leaflet.js"), "utf8");
const leafletCss = readFileSync(path.join(root, "vendor", "leaflet.css"), "utf8");
const src = readFileSync(path.join(root, "src", "client.js"), "utf8");

if (leafletCss.includes("`") || leafletCss.includes("${")) {
	throw new Error("vendor/leaflet.css now contains a backtick or ${ — the inliner contract broke; adjust the CSS injection strategy");
}
if (src.includes("__ORM_LEAFLET_CSS__") === false) {
	throw new Error("src/client.js no longer reads window.__ORM_LEAFLET_CSS__ — update this builder");
}

const banner = "// GENERATED by scripts/build-client.mjs — edit src/client.js and vendor, then rebuild. Do not edit directly.\n";
const part1 = `(function(){var module={exports:{}};var exports=module.exports;var define;
${leafletJs}
;window.L=module.exports;})();
`;
const part2 = "window.__ORM_LEAFLET_CSS__=" + JSON.stringify(leafletCss) + ";\n";
const out = banner + part1 + part2 + src;
writeFileSync(path.join(root, "client.js"), out, "utf8");
process.stdout.write(`client.js written: ${out.length} bytes (leaflet ${leafletJs.length} + css ${leafletCss.length} + src ${src.length})\n`);
